export const i18n = {
  get locale() { return state.locale },
  set locale(val) {
    state.locale = val
    localStorage.setItem('crt_locale', val)
    document.documentElement.lang = val
  },
  t(key) {
    return messages[state.locale]?.[key] || messages['ca']?.[key] || key
  },
  availableLocales: ['ca', 'es', 'en'],
  localeNames: { ca: 'Català', es: 'Castellano', en: 'English' }
}

export function useI18n() {
  return {
    t: (key) => computed(() => i18n.t(key)),
    locale: computed({
      get: () => state.locale,
      set: (val) => { i18n.locale = val }
    }),
    availableLocales: i18n.availableLocales,
    localeNames: i18n.localeNames
  }
}
